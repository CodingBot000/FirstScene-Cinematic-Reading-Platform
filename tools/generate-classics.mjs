import fs from "node:fs";
import { pathToFileURL } from "node:url";
import { format } from "prettier";

export function buildClassicSources(catalog, works) {
  const ids = new Set();
  const cards = catalog.map(
    ({ id, title, author, summary, sourceRevision }) => {
      if (
        typeof id !== "string" ||
        !/^classic-[a-z0-9-]+$/.test(id) ||
        ids.has(id)
      )
        throw new Error("CLASSIC_ID_INVALID_OR_DUPLICATE:" + id);
      ids.add(id);
      const work = works.get(id);
      if (!work) throw new Error("CLASSIC_MANUSCRIPT_MISSING:" + id);
      if (
        typeof work.text !== "string" ||
        !work.text.trim() ||
        !title ||
        !author ||
        !summary ||
        !sourceRevision ||
        work.sourceRevision !== sourceRevision ||
        work.title !== title ||
        work.author !== author
      )
        throw new Error("CLASSIC_MANUSCRIPT_METADATA_MISMATCH:" + id);
      return { id, title, author, summary };
    },
  );
  for (const id of works.keys())
    if (!ids.has(id)) throw new Error("CLASSIC_MANUSCRIPT_UNLISTED:" + id);
  const loaders = [...ids]
    .sort()
    .map(
      (id) =>
        `${JSON.stringify(id)}: () => import("../../../content/classics/works/${id}.json"),`,
    );
  return {
    cards: `// Generated by tools/generate-classics.mjs\nexport const classicCards = ${JSON.stringify(cards)};\n`,
    loaders: `// Generated by tools/generate-classics.mjs\nexport const classicLoaders = {\n${loaders.join("\n")}\n};\n`,
  };
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const read = (file) => JSON.parse(fs.readFileSync(file, "utf8"));
  const index = read("content/classics/catalog.json");
  const works = new Map(
    fs
      .readdirSync("content/classics/works")
      .filter((file) => file.endsWith(".json"))
      .map((file) => [
        file.slice(0, -5),
        read("content/classics/works/" + file),
      ]),
  );
  const outputs = buildClassicSources(index, works);
  for (const [name, source] of Object.entries(outputs)) {
    const path = `apps/web/lib/classic-${name}.generated.ts`;
    const text = await format(source, { parser: "typescript" });
    if (process.argv.includes("--check")) {
      if (!fs.existsSync(path) || fs.readFileSync(path, "utf8") !== text)
        throw new Error("CLASSIC_GENERATED_OUTPUT_STALE:" + path);
    } else fs.writeFileSync(path, text);
  }
}
